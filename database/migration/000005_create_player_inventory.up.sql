CREATE TABLE IF NOT EXISTS player_cards (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    uid UUID NOT NULL REFERENCES players(uid) ON DELETE CASCADE,
    card_id VARCHAR(64) NOT NULL REFERENCES cards(card_id),
    level INT NOT NULL DEFAULT 1,
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    obtained_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_player_cards_uid ON player_cards (uid);

CREATE TABLE IF NOT EXISTS player_items (
    uid UUID NOT NULL REFERENCES players(uid) ON DELETE CASCADE,
    item_id VARCHAR(64) NOT NULL REFERENCES items(item_id),
    quantity BIGINT NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (uid, item_id)
);
