// levelseed 產生 database/seed/<version>/level_exp_card.sql（卡片升級所需經驗表）。
package main

import (
	"flag"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"strings"
)

const (
	maxLevel        = 300         // 卡片等級上限，表有 maxLevel-1 列
	startExp        = 1_000       // 1 級升 2 級所需經驗
	earlyRows       = 100         // 前段列數（1~100 級）：分四段、成長率逐段遞減
	earlyBandTotal  = 1_500_000   // 前段最後 10 列（91~100 級）的經驗總和
	totalExp        = 200_000_000 // 1 ~ maxLevel-1 列的經驗總和（約略值，取整後有數個點的誤差）
	rowsPerBand     = 10
	floatEpsilon    = 1e-9 // 避免浮點誤差讓整數值被向上取整多 1
	outputFileName  = "level_exp_card.sql"
	outputKind      = "card"
	outputHeaderFmt = "-- Code generated by cmd/levelseed. DO NOT EDIT.\n-- kind=%s，level 為目前等級，exp_required 為升到下一級所需經驗，等級上限 %d。\n\n"
)

// earlySegments 為前段的四段（1~30、30~50、50~80、80~100 級）：steps 為該段的升級列數，
// shape 為該段成長率的相對形狀（逐段遞減）；實際成長率為 shape 的 k 次方，k 由 earlyBandTotal 解出。
var earlySegments = []struct {
	steps int
	shape float64
}{
	{29, 1.10},
	{20, 1.08},
	{30, 1.06},
	{20, 1.04},
}

func main() {
	seedDir := flag.String("seed-dir", "../database/seed", "seed 根目錄")
	flag.Parse()
	if flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "Usage: levelseed [-seed-dir dir] <seed-version>")
		os.Exit(1)
	}
	out := filepath.Join(*seedDir, flag.Arg(0), outputFileName)
	if err := os.WriteFile(out, []byte(render(cardCurve())), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "levelseed:", err)
		os.Exit(1)
	}
	fmt.Println("generated", out)
}

// cardCurve 回傳 1 ~ maxLevel-1 級各自升到下一級所需的經驗（index 0 為 1 級）。
//
// 前 earlyRows 列：從 startExp 起，依 earlySegments 分四段以固定比例成長（成長率逐段遞減），
// 整體縮放到最後 10 列（91~100 級）合計 earlyBandTotal。
// 之後每一列乘上同一個比例（也就是每 10 列為前一段的固定倍數），比例解到全部列合計 totalExp，
// 並與前段平滑銜接。每一級取整後保證比上一級多。
func cardCurve() []int64 {
	k := bisect(1e-3, 1.5, func(k float64) float64 {
		rows := earlyCurve(k)
		return sum(rows[earlyRows-rowsPerBand:]) - earlyBandTotal
	})
	early := earlyCurve(k)

	step := bisect(1.0, 1.5, func(step float64) float64 {
		return sum(early) + sum(lateCurve(early[earlyRows-1], step)) - totalExp
	})
	rows := append(early, lateCurve(early[earlyRows-1], step)...)

	need := make([]int64, 0, len(rows))
	for i, v := range rows {
		n := int64(math.Ceil(v - floatEpsilon))
		if i > 0 && n <= need[i-1] {
			n = need[i-1] + 1
		}
		need = append(need, n)
	}
	return need
}

// earlyCurve 回傳前段 earlyRows 列（浮點，未取整）。
func earlyCurve(k float64) []float64 {
	rows := make([]float64, 0, earlyRows)
	rows = append(rows, startExp)
	for _, seg := range earlySegments {
		growth := math.Pow(seg.shape, k)
		for i := 0; i < seg.steps; i++ {
			rows = append(rows, rows[len(rows)-1]*growth)
		}
	}
	return rows
}

// lateCurve 回傳前段之後的列（浮點，未取整），每列為前一列乘 step。
func lateCurve(last, step float64) []float64 {
	rows := make([]float64, 0, maxLevel-1-earlyRows)
	for len(rows) < maxLevel-1-earlyRows {
		last *= step
		rows = append(rows, last)
	}
	return rows
}

func sum(rows []float64) float64 {
	var total float64
	for _, v := range rows {
		total += v
	}
	return total
}

// bisect 在 [lo, hi] 內找 f 的零點，f 須為遞增函數。
func bisect(lo, hi float64, f func(float64) float64) float64 {
	for i := 0; i < 100; i++ {
		mid := (lo + hi) / 2
		if f(mid) > 0 {
			hi = mid
		} else {
			lo = mid
		}
	}
	return (lo + hi) / 2
}

func render(need []int64) string {
	var sb strings.Builder
	fmt.Fprintf(&sb, outputHeaderFmt, outputKind, len(need)+1)
	sb.WriteString("INSERT INTO level_exp (kind, level, exp_required)\nVALUES\n")
	for i, n := range need {
		sep := ","
		if i == len(need)-1 {
			sep = ""
		}
		fmt.Fprintf(&sb, "    ('%s', %d, %d)%s\n", outputKind, i+1, n, sep)
	}
	sb.WriteString("ON CONFLICT (kind, level) DO UPDATE SET exp_required = EXCLUDED.exp_required;\n")
	return sb.String()
}
