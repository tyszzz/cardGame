// cardseed 讀取 database/seed/<version>/cards/*.json，輸出 database/seed/<version>/cards.sql。
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"cardGame/model/cards"
)

const (
	maxCardIDLen   = 64
	maxCardNameLen = 100
)

func main() {
	seedDir := flag.String("seed-dir", "../database/seed", "seed 根目錄")
	flag.Parse()
	if flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "Usage: cardseed [-seed-dir dir] <seed-version>")
		os.Exit(1)
	}

	versionDir := filepath.Join(*seedDir, flag.Arg(0))
	out := filepath.Join(versionDir, "cards.sql")
	if err := generate(filepath.Join(versionDir, "cards"), out); err != nil {
		fmt.Fprintln(os.Stderr, "cardseed:", err)
		os.Exit(1)
	}
	fmt.Println("generated", out)
}

func generate(jsonDir, outFile string) error {
	files, err := filepath.Glob(filepath.Join(jsonDir, "*.json"))
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("no JSON files found in %s", jsonDir)
	}
	sort.Strings(files)

	seen := make(map[string]string, len(files))
	var sb strings.Builder
	sb.WriteString("-- Code generated by cmd/cardseed from cards/*.json. DO NOT EDIT.\n\n")
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		card, err := parseCard(data)
		if err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		if prev, ok := seen[card.def.CardID]; ok {
			return fmt.Errorf("%s: duplicate cardId %q (also in %s)", file, card.def.CardID, prev)
		}
		seen[card.def.CardID] = file
		sb.WriteString(card.sql())
	}
	return os.WriteFile(outFile, []byte(sb.String()), 0o644)
}

type parsedCard struct {
	def         cards.CardDefinition
	baseConfig  string
	skillConfig string
}

func parseCard(data []byte) (*parsedCard, error) {
	var def cards.CardDefinition
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&def); err != nil {
		return nil, err
	}
	if err := validate(&def); err != nil {
		return nil, err
	}

	// JSONB 內容保留原始 JSON，避免 struct 序列化補上未填的空欄位。
	var raw struct {
		BaseConfig  json.RawMessage `json:"baseConfig"`
		SkillConfig json.RawMessage `json:"skillConfig"`
	}
	if err := json.Unmarshal(data, &raw); err != nil {
		return nil, err
	}
	base, err := compactOrEmpty(raw.BaseConfig)
	if err != nil {
		return nil, fmt.Errorf("baseConfig: %w", err)
	}
	skill, err := compactOrEmpty(raw.SkillConfig)
	if err != nil {
		return nil, fmt.Errorf("skillConfig: %w", err)
	}
	return &parsedCard{def: def, baseConfig: base, skillConfig: skill}, nil
}

func validate(def *cards.CardDefinition) error {
	if def.CardID == "" || len(def.CardID) > maxCardIDLen {
		return fmt.Errorf("cardId must be 1-%d bytes", maxCardIDLen)
	}
	if def.CardName == "" || len(def.CardName) > maxCardNameLen {
		return fmt.Errorf("cardName must be 1-%d bytes", maxCardNameLen)
	}
	if !def.Rarity.Valid() {
		return fmt.Errorf("invalid rarity: %d", def.Rarity)
	}
	if !def.Race.Valid() {
		return fmt.Errorf("invalid race: %d", def.Race)
	}
	b := def.BaseConfig
	if b.Attack < 0 || b.Defense < 0 || b.Health < 0 {
		return fmt.Errorf("baseConfig attack/defense/health must not be negative")
	}
	if b.AttackRatio < 0 || b.DefenseRatio < 0 || b.HealthRatio < 0 {
		return fmt.Errorf("baseConfig ratios must not be negative")
	}
	return validateSkills(def.Rarity, &def.SkillConfig)
}

func compactOrEmpty(raw json.RawMessage) (string, error) {
	if len(raw) == 0 || string(raw) == "null" {
		return "{}", nil
	}
	var buf bytes.Buffer
	if err := json.Compact(&buf, raw); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

func (c *parsedCard) sql() string {
	d := c.def
	return fmt.Sprintf(`INSERT INTO cards (card_id, card_name, rarity, race, base_config, skill_config, is_enabled)
VALUES (%s, %s, %d, %d, %s::jsonb, %s::jsonb, %t)
ON CONFLICT (card_id) DO UPDATE SET
    card_name = EXCLUDED.card_name,
    rarity = EXCLUDED.rarity,
    race = EXCLUDED.race,
    base_config = EXCLUDED.base_config,
    skill_config = EXCLUDED.skill_config,
    is_enabled = EXCLUDED.is_enabled,
    updated_at = CURRENT_TIMESTAMP;

`, quote(d.CardID), quote(d.CardName), d.Rarity, d.Race, quote(c.baseConfig), quote(c.skillConfig), d.IsEnabled)
}
